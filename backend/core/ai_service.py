    def __init__(self):
        self.models_loaded = {}
        self.is_debug = settings.DEBUG

        if not self.is_debug:
            self._load_models()

    def _load_models(self):
        """Load production models (only in production)"""
        try:
            import torch
            from transformers import AutoModelForCausalLM, AutoTokenizer

            for model_id, config in settings.LEXA_MODELS.items():
                model_path = config.get('model_path')
                if model_path:
                    logger.info(f"Loading model: {model_id} from {model_path}")
                    try:
                        tokenizer = AutoTokenizer.from_pretrained(model_path)
                        model = AutoModelForCausalLM.from_pretrained(
                            model_path,
                            torch_dtype=torch.float16 if torch.cuda.is_available() else torch.float32,
                            device_map='auto',
                        )
                        self.models_loaded[model_id] = {
                            'model': model,
                            'tokenizer': tokenizer,
                        }
                        logger.info(f"Model {model_id} loaded successfully")
                    except Exception as e:
                        logger.error(f"Failed to load {model_id}: {e}")
        except ImportError:
            logger.warning("PyTorch/Transformers not available")

    def stream_response(
        self,
        prompt: str,
        history: List[Dict],
        model_id: str,
        user
    ) -> Generator[Dict[str, Any], None, None]:
        """
        Stream AI response token by token.
        Yields dicts with type='text' or type='done'
        """
        if self.is_debug:
            yield from self._demo_stream(prompt, model_id)
        else:
            yield from self._production_stream(prompt, history, model_id, user)

    def _demo_stream(self, prompt: str, model_id: str) -> Generator[Dict, None, None]:
        """Demo streaming with realistic delay"""
        # Select a contextual response
        response = self._get_contextual_demo_response(prompt)

        total_tokens = 0
        words = response.split(' ')

        for i, word in enumerate(words):
            chunk = word + (' ' if i < len(words) - 1 else '')
            yield {'type': 'text', 'text': chunk}
            total_tokens += 1
            time.sleep(0.03)  # Simulate token generation speed

        yield {'type': 'done', 'tokens': total_tokens}

