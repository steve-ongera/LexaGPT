    def _production_stream(
        self,
        prompt: str,
        history: List[Dict],
        model_id: str,
        user
    ) -> Generator[Dict, None, None]:
        """Production inference with real models"""
        try:
            import torch

            if model_id not in self.models_loaded:
                # Fallback to demo if model not loaded
                yield from self._demo_stream(prompt, model_id)
                return

            model_data = self.models_loaded[model_id]
            model = model_data['model']
            tokenizer = model_data['tokenizer']

            # Build prompt with history
            conversation_text = self._build_conversation_prompt(prompt, history, tokenizer)

            inputs = tokenizer.encode(conversation_text, return_tensors='pt')
            if torch.cuda.is_available():
                inputs = inputs.cuda()

            # Get max tokens from plan
            max_tokens = settings.SUBSCRIPTION_PLANS.get(
                user.current_plan, {}
            ).get('features', {}).get('max_context_tokens', 8192)

            total_tokens = 0
            with torch.no_grad():
                for output in self._generate_streaming(model, inputs, max_new_tokens=min(2048, max_tokens)):
                    token_text = tokenizer.decode([output], skip_special_tokens=True)
                    if token_text:
                        yield {'type': 'text', 'text': token_text}
                        total_tokens += 1

            yield {'type': 'done', 'tokens': total_tokens}

        except Exception as e:
            logger.error(f"Production inference error: {e}")
            yield from self._demo_stream(prompt, model_id)

    def _build_conversation_prompt(self, prompt: str, history: List[Dict], tokenizer) -> str:
        """Build full conversation prompt from history"""
        messages = []
        messages.append({"role": "system", "content": "You are Lexa, a helpful AI assistant created by LexaGPT."})
        for msg in history[-20:]:  # Last 20 messages for context
            messages.append({"role": msg['role'], "content": msg['content']})
        messages.append({"role": "user", "content": prompt})

        # Try chat template if available
        if hasattr(tokenizer, 'apply_chat_template'):
            return tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)

        # Fallback format
        text = "System: You are Lexa, a helpful AI assistant.\n\n"
        for msg in messages[1:]:
            prefix = "Human: " if msg['role'] == 'user' else "Assistant: "
            text += f"{prefix}{msg['content']}\n"
        text += "Assistant: "
        return text

    def _generate_streaming(self, model, inputs, max_new_tokens=2048):
        """Yield tokens one by one"""
        import torch
        from transformers import StoppingCriteria, StoppingCriteriaList

        generated = inputs
        for _ in range(max_new_tokens):
            with torch.no_grad():
                outputs = model(generated)
                next_token = outputs.logits[:, -1, :].argmax(dim=-1)
                generated = torch.cat([generated, next_token.unsqueeze(0)], dim=-1)
                yield next_token.item()
                # Stop on EOS
                if next_token.item() == model.config.eos_token_id:
                    break